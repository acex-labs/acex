#!/usr/bin/env bash
# Regenerates the pinned third-party dependencies of the backend and worker images:
# backend/constraints.txt and worker/constraints.txt, which the Dockerfiles pass to pip with -c.
#
# The constraints file is emptied and the image is built from its real Dockerfile without any cache, so pip
# resolves the newest versions the pyprojects allow today. The versions it installed are read back with
# pip freeze, without the project's own acex* packages and pip, and written to the constraints file.
# Every run is therefore an upgrade of all third-party packages: review the diff and test before you commit.
#
# Usage:
#   scripts/lock-images.sh [backend|worker|all]     (default: all)
#
# Needs bash and docker. The images are built for linux/amd64, the first platform CI publishes and the one the
# image build check uses. LOCK_PLATFORM=linux/arm64 builds for the other one.
# The constraints file is put back if the script fails or is interrupted, and the temporary images
# (acex-pin-<image>-<pid>) are removed when it ends.

set -euo pipefail

PLATFORM="${LOCK_PLATFORM:-linux/amd64}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP="$(mktemp -d "${TMPDIR:-/tmp}/lock-images.XXXXXX")"
TAG=""
TARGET=""
LOCKED=""

fail() {
    echo "lock-images: $*" >&2
    exit 1
}

cleanup() {
    if [ -n "$TAG" ]; then
        docker rmi "$TAG" >/dev/null 2>&1 || true
    fi
    # Put back the file that was emptied for the build.
    if [ -n "$TARGET" ]; then
        if [ -f "$TMP/old" ]; then
            cp "$TMP/old" "$TARGET"
        else
            rm -f "$TARGET"
        fi
    fi
    rm -rf "$TMP"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

lock_image() {
    local name="$1"
    local file="$ROOT/$name/constraints.txt"

    TAG="acex-pin-$name-$$"
    rm -f "$TMP/old"
    if [ -f "$file" ]; then
        cp "$file" "$TMP/old"
    fi
    TARGET="$file"
    : > "$file"

    echo "Building $name for $PLATFORM without pins"
    # Without --no-cache a cached pip layer would hand back the versions of an earlier build.
    docker build --no-cache --platform "$PLATFORM" -f "$ROOT/$name/Dockerfile" -t "$TAG" "$ROOT"
    docker image inspect "$TAG" >/dev/null 2>&1 ||
        fail "the build left no image in Docker (a docker-container builder does not load it), try: docker buildx use default"

    docker run --rm --platform "$PLATFORM" --entrypoint python "$TAG" -m pip freeze --all > "$TMP/freeze"

    # The project's own packages are listed as "acex-... @ file:///deps/...", pip belongs to the base image.
    grep -v -i -E '^(acex|pip==)' "$TMP/freeze" > "$TMP/pins" || true
    [ -s "$TMP/pins" ] || fail "pip freeze in the $name image listed no third-party packages"
    not_a_pin="$(grep -v -E '^[A-Za-z0-9._-]+==[A-Za-z0-9._+!-]+$' "$TMP/pins" || true)"
    if [ -n "$not_a_pin" ]; then
        fail "pip freeze in the $name image printed lines that are not plain pins:"$'\n'"$not_a_pin"
    fi

    {
        echo "# Third-party dependencies of the $name image, pinned so that two builds of the same source"
        echo "# install the same versions. The project's own acex* packages are installed from this repository"
        echo "# and are not listed, and pip comes with the base image."
        echo "#"
        echo "# Generated by scripts/lock-images.sh from a build of $name/Dockerfile for $PLATFORM."
        echo "# Do not edit by hand. To refresh, run scripts/lock-images.sh $name, review the diff and commit it."
        LC_ALL=C sort -t= -k1,1 -f "$TMP/pins"
    } > "$TMP/new"
    cp "$TMP/new" "$file"
    TARGET=""

    if [ -f "$TMP/old" ] && cmp -s "$TMP/old" "$file"; then
        echo "$name/constraints.txt: unchanged"
    else
        echo "$name/constraints.txt: written, $(grep -c '==' "$file") packages"
    fi
    LOCKED="$LOCKED $name/constraints.txt"

    docker rmi "$TAG" >/dev/null
    TAG=""
}

command -v docker >/dev/null || fail "docker is not installed"

case "${1:-all}" in
    backend | worker) lock_image "$1" ;;
    all)
        lock_image backend
        lock_image worker
        ;;
    *)
        echo "Usage: scripts/lock-images.sh [backend|worker|all]" >&2
        exit 2
        ;;
esac

echo
echo "Review the changes before you commit them, every third-party package may have moved:"
echo "  git diff --$LOCKED"
